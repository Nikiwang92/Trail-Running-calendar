def split_province_city(city_str):
    """从 city 字符串推断 (province, city)
    返回 (province, city)。city 优先保留原字符串。
    """
    if not city_str:
        return ('', '')
    s = str(city_str).strip()
    # 港澳台：仅当地点以"香港/澳门/台湾"开头（"中国香港 香港 …"）；避免"炮台湾"误判
    s2 = s[2:] if s.startswith('中国') else s
    for k in ('香港', '澳门', '台湾'):
        if s2.startswith(k):
            return (k, s)
    # 直辖市
    for p in DIRECT_MUNICIPALITIES:
        if s.startswith(p):
            return (p, s)
    # 显式省份开头
    for p in PROVINCES:
        if s.startswith(p):
            rest = s[len(p):]
            if rest:
                return (p, p + rest)
            return (p, s)
    # 从城市名推断
    for city, prov in sorted(CITY_TO_PROVINCE.items(), key=lambda x: -len(x[0])):
        if s.startswith(city):
            return (prov, s)
    return ('', s)