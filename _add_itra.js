let added = 0;
const lines = html.split('\n');
const outLines = lines.map(line => {
  if (!/^\s*\{ name:/.test(line)) return line;
  // 检查该行是否属于ITRA名单
  const isItra = itraNames.some(name => line.includes(name));
  if (!isItra) return line;
  // 检查是否已有 itra 标签
  if (/tags: \[[^\]]*"itra"\]/.test(line)) return line;
  // 在 tags 数组中插入 "itra"
  const newLine = line.replace(/tags: \[([^\]]*)\]/, (m, inner) => {
    const items = inner.trim() === '' ? [] : inner.split(',').map(s => s.trim()).filter(Boolean);
    items.push('"itra"');
    return 'tags: [' + items.join(',') + ']';
  });
  added++;
  return newLine;
});

html = outLines.join('\n');
